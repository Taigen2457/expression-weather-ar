import assert from 'node:assert/strict';
import {ExpressionGate,collide} from './core.mjs';
const g=new ExpressionGate();let bursts=0;
for(let t=0;t<1000;t+=50)assert.notEqual(g.update(.03,.65,t).state,'laugh');
for(let t=1000;t<2000;t+=50)g.update(.8,.05,t);
assert.equal(g.state,'smile');
for(let t=2000;t<5000;t+=50)bursts+=Number(g.update(.85,.5,t).burst);
assert.equal(bursts,1,'A held laugh must fire only once');
for(let t=5000;t<6000;t+=50)g.update(0,0,t);
for(let t=6000;t<7500;t+=50)bursts+=Number(g.update(.85,.5,t).burst);
assert.equal(bursts,2,'Relaxing rearms the effect');
g.reset();for(let t=0;t<150;t+=50)assert.equal(g.update(.9,.8,t).burst,false);
const h={x:0,y:0,rx:50,ry:70,vx:0,vy:0,angle:0};
const p={px:-100,py:0,x:100,y:0,vx:800,vy:0};
assert.equal(collide(p,h,.05),true,'Swept collision catches complete tunnelling');assert.ok(p.vx<0);assert.ok(p.x<-50);
const miss={px:-100,py:100,x:100,y:100,vx:800,vy:0};assert.equal(collide(miss,h,.05),false);
const moving={...h,vx:200};const q={px:55,py:0,x:55,y:0,vx:0,vy:0};
assert.equal(collide(q,{...moving,x:10},.05),true);assert.ok(q.vx>0,'Moving head transfers velocity');
console.log('PASS: speech rejection, smile, laugh debounce/rearm, transient rejection, swept collision, miss, moving-head impulse.');
